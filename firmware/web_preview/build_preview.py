"""Builds index.html: the firmware's settings page, runnable in any browser without an ESP32.

The page is taken unchanged from web_ui.h. The settings list and its defaults are read
from rc_crane.ino (the settings.add() calls, the [web] variables and the AXES table), and a
small script in front of the page answers its /api/... requests in the browser:
saving works, nothing is stored, and the live values are simulated.

    python3 firmware/web_preview/build_preview.py
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SKETCH = os.path.join(HERE, "..", "rc_crane")

ino = open(os.path.join(SKETCH, "rc_crane.ino")).read()
page = re.search(r'R"HTML\((.*)\)HTML"', open(os.path.join(SKETCH, "web_ui.h")).read(), re.S).group(1)

NUM = r"(-?[\d.]+)f?"
ADD_TAIL = rf", {NUM}, {NUM}, {NUM}(?:, \"([^\"]*)\")?(?:, (true|false))?\);"

# global [web] variables: float name = value;
variables = {m[1]: float(m[2]) for m in re.finditer(rf"^float\s+(\w+)\s*=\s*{NUM};", ino, re.M)}

# AXES table rows: name, STEP, DIR, RC, addr, stroke, invert, run, home, SG, mode
axes = [
    {"name": m[1], "strokeMm": float(m[2]), "invertDir": float(m[3] == "true"), "runCurrentMa": float(m[4]),
     "homeCurrentMa": float(m[5]), "stallThreshold": float(m[6]), "mode": float(m[7] == "RATE")}
    for m in re.finditer(r'\{"([^"]+)",\s*\d+,\s*\d+,\s*\d+,\s*\d+,\s*([\d.]+)f,\s*(true|false),\s*(\d+),\s*(\d+),'
                         r'\s*(\d+),\s*ControlMode::(\w+)\}', ino)
]


def setting(key, group, label, unit, default, m):
    return {"key": key, "group": group, "label": label, "unit": unit, "value": default, "default": default,
            "min": float(m[0]), "max": float(m[1]), "step": float(m[2]), "options": m[3] or "",
            "restart": m[4] == "true"}


settings = []
for m in re.finditer(r'settings\.add\("(\w+)", "([^"]*)", "([^"]*)", "([^"]*)", &(\w+)' + ADD_TAIL, ino):
    settings.append(setting(m[1], m[2], m[3], m[4], variables[m[5]], m.groups()[5:]))
axis_adds = list(re.finditer(r'settings\.add\(k \+ "(\w+)", g, "([^"]*)", "([^"]*)", &(\w+)' + ADD_TAIL, ino))
for i, axis in enumerate(axes):
    for m in axis_adds:
        settings.append(setting(f"a{i}_{m[1]}", axis["name"], m[2], m[3], axis[m[4]], m.groups()[4:]))

assert settings and axes, "nothing found - did the sketch's settings code change?"

MOCK = """<script>
// Preview only: answers the page's API calls in the browser, no ESP32 involved.
(() => {
  const settings = %s, axes = %s, t0 = Date.now();
  const json = o => new Response(JSON.stringify(o), {headers: {'Content-Type': 'application/json'}});
  const text = t => new Response(t);
  window.fetch = async (url, opt = {}) => {
    const post = (opt.method || 'GET') === 'POST';
    if (url === '/api/settings' && !post) return json(settings);
    if (url === '/api/settings') {
      for (const [k, v] of new URLSearchParams(opt.body)) {
        const s = settings.find(s => s.key === k);
        if (s) s.value = Math.min(s.max, Math.max(s.min, Math.round((+v - s.min) / s.step) * s.step + s.min));
      }
      return text('Saved (preview: nothing is stored).');
    }
    if (url === '/api/reset') { settings.forEach(s => s.value = s.default); return text('All settings back to defaults.'); }
    if (url === '/api/restart') return text('Preview: an ESP32 would restart and home now.');
    if (url === '/api/status') {
      const t = (Date.now() - t0) / 1000, out = {uptime_s: Math.floor(t), drivers: 'off'};
      axes.forEach((a, i) => {
        const stroke = settings.find(s => s.key === 'a' + i + '_stroke').value;
        const pos = +(stroke / 2 + stroke / 2.5 * Math.sin(t / (3 + i))).toFixed(2);
        out[a] = {pos_mm: pos, target_mm: pos, rc: i ? 'no signal' : +Math.sin(t / 3).toFixed(2)};
      });
      return json(out);
    }
    return new Response('not found', {status: 404});
  };
  addEventListener('DOMContentLoaded', () => document.body.insertAdjacentHTML('afterbegin',
    '<p style="background:#fff3c4;border:1px solid #e0c060;border-radius:8px;padding:8px 12px;margin:0 0 12px">' +
    '<b>Preview</b> of the page the ESP32 serves at http://192.168.4.1. Generated from the firmware; ' +
    'saving works here but nothing is stored, the live values are simulated.</p>'));
})();
</script>
""" % (json.dumps(settings, ensure_ascii=False), json.dumps([a["name"] for a in axes]))

note = "<!-- Generated by build_preview.py from ../rc_crane/web_ui.h and rc_crane.ino - do not edit -->\n"
html = note + page.replace("<head>", "<head>\n" + MOCK, 1)
open(os.path.join(HERE, "index.html"), "w").write(html)
print(f"index.html: {len(settings)} settings, axes {', '.join(a['name'] for a in axes)}")
